#!/usr/bin/env python3
"""Generates the Android translations of server codes from the web client's locales.

The server answers with stable codes (health checks, "why isn't it here?", rejection reasons,
notification types...). The web client already translates them; this copies those texts into
app/src/main/res/values{,-hr}/codes.xml and writes ui/Codes.kt (code -> string resource), so
both clients say the same thing. Run it after the web locales change:

    python3 android/tools/gen-codes.py
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
LOCALES = ROOT / "web/src/i18n/locales"
APP = ROOT / "android/app/src/main"
# Namespaces (dotted paths into the locale files) whose leaves become string resources.
NAMESPACES = [
    "explain.codes", "board.itemCodes", "board.groups", "board.fix", "health.codes",
    "notifications.types", "rejectionCodes", "downloadStates", "requests.status",
    "timeline.events", "timeline.sources", "timeline.reasons", "timeline.indexerStatus",
    "indexers.health", "indexers.kinds", "indexers.errorKinds",
]

def leaves(obj, prefix):
    if isinstance(obj, dict):
        for k, v in obj.items():
            yield from leaves(v, f"{prefix}.{k}")
    elif isinstance(obj, str):
        yield prefix, obj

def pick(d, path):
    for k in path.split("."):
        d = d.get(k, {}) if isinstance(d, dict) else {}
    return d

def res_name(key):
    return "c_" + re.sub(r"[^a-zA-Z0-9]", "_", key).lower()

def esc(s):
    s = s.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if s[:1] in ("@", "?"):
        s = "\\" + s
    return s

def main():
    en = json.loads((LOCALES / "en.json").read_text())
    hr = json.loads((LOCALES / "hr.json").read_text())
    keys = []
    texts = {"en": {}, "hr": {}}
    for ns in NAMESPACES:
        for key, text in leaves(pick(en, ns), ns):
            # i18next plural forms (_one, _other...) are not used by the app.
            if re.search(r"_(one|few|many|other|zero)$", key):
                continue
            keys.append(key)
            texts["en"][key] = text
            hr_text = pick(hr, key)
            texts["hr"][key] = hr_text if isinstance(hr_text, str) else text
    header = "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by android/tools/gen-codes.py from web/src/i18n/locales. Do not edit. -->\n<resources>\n"
    for lang, folder in (("en", "values"), ("hr", "values-hr")):
        lines = [f'    <string name="{res_name(k)}" formatted="false">{esc(texts[lang][k])}</string>' for k in keys]
        (APP / "res" / folder / "codes.xml").write_text(header + "\n".join(lines) + "\n</resources>\n")
    kt = ["// Generated by android/tools/gen-codes.py from web/src/i18n/locales. Do not edit.",
          "package net.scyde.locarr.ui", "", "import net.scyde.locarr.R", "",
          "/** Server code (\"health.codes.indexer_failing\") to its translated text. */",
          "val CODE_STRINGS: Map<String, Int> = mapOf("]
    kt += [f'    "{k}" to R.string.{res_name(k)},' for k in keys]
    kt += [")", ""]
    (APP / "java/net/scyde/locarr/ui/Codes.kt").write_text("\n".join(kt))
    print(f"{len(keys)} strings")

if __name__ == "__main__":
    main()
